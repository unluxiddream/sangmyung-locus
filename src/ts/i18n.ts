"use strict";

type Lang = "ko" | "en" | "ja";

interface LanguageInfo {
  lang: Lang;
  code: string;
  label: string;
}

const LANGUAGES: LanguageInfo[] = [
  { lang: "ko", code: "KOR", label: "한국어" },
  { lang: "en", code: "ENG", label: "English" },
  { lang: "ja", code: "JPN", label: "日本語" },
];
const LANGUAGE_STORAGE_KEY = "locus-lang";

function isLang(value: string | null | undefined): value is Lang {
  return LANGUAGES.some((item) => item.lang === value);
}

// ?lang=en 주소가 가장 우선, 그다음 마지막으로 고른 언어, 없으면 한국어
function detectLanguage(): Lang {
  const requested = new URLSearchParams(location.search).get("lang");
  if (isLang(requested)) return requested;
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (isLang(saved)) return saved;
  } catch {
    // 저장소를 쓸 수 없는 환경(사생활 보호 모드 등)에서는 기본 언어 사용
  }
  return "ko";
}

const LANG: Lang = detectLanguage();
document.documentElement.lang = LANG;

function setLanguage(lang: Lang): void {
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
  } catch {
    // 저장이 안 되면 이번 페이지만 주소로 전환
  }
  const url = new URL(location.href);
  url.searchParams.delete("lang");
  if (lang !== "ko") url.searchParams.set("lang", lang);
  location.href = url.href;
}

